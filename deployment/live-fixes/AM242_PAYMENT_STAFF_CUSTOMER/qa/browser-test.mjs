import { chromium } from 'playwright';
import fs from 'node:fs';
const base=(process.env.STAGING_BASE_URL||'https://staging.assammotors.com').replace(/\/$/,'');
const email=process.env.STAGING_ADMIN_LOGIN||'';
const password=process.env.STAGING_ADMIN_PASSWORD||'';
const loginPath=process.env.STAGING_LOGIN_PATH||'/erp/login';
const out=process.env.SMOKE_OUTPUT_DIR||'am242-browser-proof';
fs.mkdirSync(out,{recursive:true});
if(!email||!password)throw new Error('Missing staging Admin QA credentials');
const browser=await chromium.launch({headless:true});
const page=await browser.newPage({viewport:{width:1440,height:920}});
const errors=[];let currentStage='login';
page.on('pageerror',e=>{
 const info={stage:currentStage,url:page.url(),message:e.message,stack:String(e.stack||'').slice(0,700)};
 errors.push(info);console.log('AM242_BROWSER_JS_ERROR '+JSON.stringify(info));
});
try{
 await page.goto(base+loginPath,{waitUntil:'domcontentloaded',timeout:45000});
 await page.locator('input[type="email"],input[name="email"],input[name="username"]').first().fill(email);
 await page.locator('input[type="password"]').first().fill(password);
 await page.locator('button[type="submit"],input[type="submit"]').first().click();
 await page.waitForLoadState('networkidle').catch(()=>{});
 currentStage='payment';
 const res=await page.goto(base+'/erp/payments/create',{waitUntil:'networkidle',timeout:45000});
 if(!res||res.status()!==200)throw new Error('Payment Voucher HTTP '+res?.status());
 const search=page.locator('#am237-payee-search'),options=page.locator('#am237-payee-results');
 await search.waitFor({state:'visible'});
 const staffOptions=await page.locator('#am231-staff-select option[value]:not([value=""])').count();
 const customerOptions=await page.locator('#am231-customer-select option[value]:not([value=""])').count();
 if(staffOptions<6)throw new Error('Missing Staff Master options: '+staffOptions);
 if(customerOptions<30)throw new Error('Canonical Customer Master not loaded: '+customerOptions);
 console.log('AM242_MASTER_OPTION_COUNTS STAFF='+staffOptions+' CUSTOMERS='+customerOptions);
 const enterType=async text=>{
   await search.fill(text);
   await options.waitFor({state:'visible'});
 };
 await enterType('Staff');
 let staffResults=options.locator('button.am237-result').filter({has:page.locator('.am237-tag',{hasText:'Staff'})});
 if(await staffResults.count()<6)throw new Error('Staff results search incomplete');
 await staffResults.first().click();
 await page.locator('#am240-staff-panel').waitFor({state:'visible'});
 await page.locator('#am237-mode').selectOption('ADVANCE');
 const staffId=await page.locator('#am231-staff-select').inputValue();
 if(!staffId)throw new Error('Staff ID not selected from Master');
 await page.locator('#payment-value').fill('1500');
 await page.locator('input[name=account_name]').fill('Cash');
 await page.locator('textarea[name=notes]').fill('Salary Advance test UI without posting');
 await page.waitForTimeout(400);
 const staffReady=!(await page.locator('#p133-save').isDisabled());
 if(!staffReady)throw new Error('Staff Advance not ready after valid form fields');
 if((await page.locator('#am240-kind-value').inputValue())!=='SALARY_ADVANCE')throw new Error('Staff Advance backend type not set');
 if(!(await page.locator('a[href*="/expenses/create"]').count()))throw new Error('Staff Expense quick link missing');
 await page.screenshot({path:out+'/staff-advance-payment-ready.png',fullPage:false});
 await enterType('Customer');
 const customers=options.locator('button.am237-result').filter({has:page.locator('.am237-tag',{hasText:'Customer'})});
 if(await customers.count()<30)throw new Error('Customer search still showing incomplete master');
 await customers.first().click();
 await page.locator('#am242-customer-panel').waitFor({state:'visible'});
 await page.locator('#am237-mode').selectOption('ADVANCE');
 if(!(await page.locator('#am231-customer-select').inputValue()))throw new Error('Canonical Customer ID not selected');
 await page.locator('#payment-value').fill('100');
 await page.locator('input[name=account_name]').fill('Cash');
 await page.locator('textarea[name=notes]').fill('Customer Advance QA UI only, do not submit');
 await page.waitForTimeout(400);
 if(await page.locator('#p133-save').isDisabled()){
   throw new Error('Customer Advance not ready even after valid master selection / fields');
 }
 if((await page.locator('#am242-customer-against').inputValue())!=='ADVANCE')throw new Error('Customer Advance source missing');
 if(await page.locator('#am231-customer-select').isDisabled())throw new Error('Customer Master hidden ID remains disabled');
 await page.screenshot({path:out+'/customer-advance-payment-ready.png',fullPage:false});
 await page.locator('#am237-mode').selectOption('AGAINST');
 await page.waitForTimeout(200);
 const credit=await page.locator('#am242-credit').innerText();
 if(!credit.includes('Customer Ledger'))throw new Error('Customer refund balance display missing');
 await page.screenshot({path:out+'/customer-refund-credit-check.png',fullPage:false});
 currentStage='expenses';
 const exp=await page.goto(base+'/erp/expenses/create',{waitUntil:'networkidle',timeout:45000});
 if(!exp||exp.status()!==200)throw new Error('Expense create HTTP '+exp?.status());
 const travel=page.locator('select[name="expense_category"] option[value="TRAVEL"]');
 if(!(await travel.innerText()).includes('LOCAL CONVEYANCE'))throw new Error('Tour / Local Conveyance option not clear');
 if(!(await page.locator('#am233-staff-id option[value]:not([value=""])').count()>=6))throw new Error('Expense Staff Master incomplete');
 await page.screenshot({path:out+'/staff-tour-local-conveyance-entry.png',fullPage:false});
 if(errors.length)throw new Error('Browser JavaScript errors by stage: '+JSON.stringify(errors.slice(0,5)));
 console.log('AM242_STAFF_CUSTOMER_PICKERS_AND_EXPENSE_UI_BROWSER_PASS_NO_PAYMENT_POST');
 fs.writeFileSync(out+'/result.json',JSON.stringify({ok:true,staffOptions,customerOptions,staffAdvanceReady:true,customerAdvanceReady:true,noMoneyPosted:true,checked:new Date().toISOString()},null,2));
}catch(e){
 await page.screenshot({path:out+'/failure.png',fullPage:false}).catch(()=>{});
 fs.writeFileSync(out+'/result.json',JSON.stringify({ok:false,error:String(e?.message||e)},null,2));
 throw e;
}finally{await browser.close()}
