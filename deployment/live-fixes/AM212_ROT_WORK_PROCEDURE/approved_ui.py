#!/usr/bin/env python3
"""AM212 approved ROT components-only copy, post AM212 source install.
Read-only check / guarded apply; does not touch DB, rates, GST or history.
Usage: approved_ui.py check|apply STAGING_ROOT
"""
from pathlib import Path
import os,sys,hashlib,tempfile,subprocess
if len(sys.argv)!=3 or sys.argv[1] not in ("check","apply"):
    raise SystemExit("AM212_COPY_USAGE check|apply STAGING_ROOT")
mode=sys.argv[1]
root=Path(sys.argv[2]).expanduser().resolve()
if root.name!="assam-erp-staging" or not (root/"artisan").is_file():
    raise SystemExit("AM212_COPY_STOP_NOT_STAGING")
p=root/"resources/views/admin/native/labour.blade.php"
if not p.is_file():raise SystemExit("AM212_COPY_STOP_VIEW_MISSING")
src=p.read_text(encoding="utf8",errors="surrogateescape")
if src.count("AM212_ROT_WORK_PROCEDURE")!=1 or src.count('name="work_procedure"')!=2:
    raise SystemExit("AM212_COPY_STOP_FIELD_NOT_INSTALLED_IN_BOTH_FORMS")
old_label="Work Procedure / Technical Instructions (Internal, optional)"
new_label="Parts / Components to Remove &amp; Refit"
old_placeholder="Removal, disconnection, fitting, torque, verification steps..."
new_placeholder=("Both rear wheels, rear brake drums, handbrake cables, "
 "brake hose/pipe brackets, ABS sensor wiring, shock lower bolts, "
 "coil springs, torsion beam mounting bolts.")
old_note="Admin reference only. Separate from ROT description; not printed on invoices."
new_note="Workshop reference only. Not printed on Estimate / Invoice."
helper="Mention only the parts/components that must be removed, disconnected and refitted to perform this ROT."
# Same source template occurs only once, as both Create/Edit are generated by AM212.
if new_label in src and helper in src:
    if old_label in src or old_placeholder in src or old_note in src:
        raise SystemExit("AM212_COPY_STOP_MIXED_COPY")
    print("AM212_APPROVED_ROT_COMPONENTS_COPY_ALREADY_PRESENT")
    sys.exit(0)
if any(src.count(s)!=1 for s in (old_label,old_placeholder,old_note)):
    raise SystemExit("AM212_COPY_STOP_SOURCE_LABEL_ANCHORS_CHANGED")
# The generated Create and Edit controls both share the same text.
new=src.replace(old_label,new_label).replace(old_placeholder,new_placeholder).replace(old_note,new_note)
anchor=(
    '      <small style="display:block;color:#647c90;line-height:1.4;margin-top:4px">'
)
if new.count(anchor)!=2:
    raise SystemExit("AM212_COPY_STOP_TWO_NOTE_ANCHORS_REQUIRED")
help_markup=(
    '<span class="am212-components-helper" style="display:block;'
    'font-size:11px;color:#486780;margin-top:4px;line-height:1.45">'
    +helper+'</span>\n      '
)
new=new.replace(anchor,help_markup+anchor)
if (new.count(new_label)!=2 or new.count(helper)!=2
    or new.count(new_placeholder)!=2 or new.count(new_note)!=2):
    raise SystemExit("AM212_COPY_STOP_BOTH_FORMS_NOT_UPDATED")
if new.count('name="work_procedure"')!=src.count('name="work_procedure"'):
    raise SystemExit("AM212_COPY_STOP_FIELD_NAMES_CHANGED")
# Only browser-facing text is changed; all Blade form routes/POST inputs remain.
with tempfile.TemporaryDirectory(prefix="am212copy_") as d:
    t=Path(d)
    (t/"view.blade.php").write_text(new,encoding="utf8",errors="surrogateescape")
    (t/"compile.php").write_text(r"""<?php
require $argv[1].'/vendor/autoload.php';
$app=require $argv[1].'/bootstrap/app.php';
$app->make(\Illuminate\Contracts\Console\Kernel::class)->bootstrap();
file_put_contents($argv[3],$app->make('blade.compiler')->compileString(file_get_contents($argv[2])));
""",encoding="utf8")
    out=t/"compiled.php"
    x=subprocess.run(["php",str(t/"compile.php"),str(root),
        str(t/"view.blade.php"),str(out)],cwd=root,capture_output=True,text=True,timeout=40)
    if x.returncode or not out.is_file():
        raise SystemExit("AM212_COPY_STOP_BLADE_COMPILE "+x.stderr[-320:])
    x=subprocess.run(["php","-l",str(out)],cwd=root,capture_output=True,text=True,timeout=20)
    if x.returncode:raise SystemExit("AM212_COPY_STOP_BLADE_LINT "+x.stderr[-320:])
print("AM212_APPROVED_COMPONENTS_COPY_PREFLIGHT_PASS")
if mode=="check":
    print("AM212_APPROVED_COPY_CHECK_NO_WRITES")
    sys.exit(0)
backup=root/"storage/app/am-backups/AM212_ROT_WORK_PROCEDURE/ROT_COMPONENTS_APPROVED_COPY_BEFORE.blade.php"
if backup.exists():raise SystemExit("AM212_COPY_STOP_BACKUP_EXISTS")
backup.parent.mkdir(parents=True,exist_ok=True)
backup.write_text(src,encoding="utf8",errors="surrogateescape")
os.chmod(backup,0o600)
fd,tmp=tempfile.mkstemp(prefix=".am212copy_",dir=p.parent)
try:
    with os.fdopen(fd,"w",encoding="utf8",errors="surrogateescape") as h:h.write(new)
    os.chmod(tmp,p.stat().st_mode & 0o777)
    os.replace(tmp,p)
finally:
    if os.path.exists(tmp):os.unlink(tmp)
x=subprocess.run(["php","artisan","view:clear"],cwd=root,text=True,capture_output=True,timeout=50)
if x.returncode:
    p.write_text(src,encoding="utf8",errors="surrogateescape")
    raise SystemExit("AM212_COPY_VIEW_CLEAR_FAILED_RESTORED")
print("AM212_APPROVED_COMPONENTS_COPY_INSTALLED_CREATE_EDIT")
print("AM212_COPY_NO_MASTER_DATA_CHANGED")
